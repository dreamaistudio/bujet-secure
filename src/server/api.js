// GET /api/sync/status - status of sync service, client count, and IP (requires localhost or Bearer auth)
router.get('/sync/status', (req, res) => {
  if (!isLoopback(req)) {
    const authHeader = req.headers.authorization;
    const clientToken = authHeader?.startsWith('Bearer ') ? authHeader.substring(7) : '';
    if (!safeCompareTokens(clientToken, syncToken)) {
      return res.status(403).json({ error: 'Forbidden: Requires valid authentication or localhost access' });
    }
  }
  const includeSecret = isLoopback(req);
  try {
    // Count phones only. The desktop window keeps its own local (loopback)
    // connection open, so counting every socket made the PC report
    // "1 phone connected" even when no phone was paired.
    const count = wsService.getMobileClientCount();
    const availableIps = getCandidateIps();
    const bestIp = availableIps.length > 0 ? availableIps[0].ip : '127.0.0.1';
    res.json({
      connectedClients: count,
      connectedCount: count,
      ip: bestIp,
      availableIps: availableIps,
      port: 3001,
      token: syncToken,
      // The lock secret goes only to this PC's own window, never out over the
      // network — otherwise a sniffed token would hand over the lock too.
      key: includeSecret ? syncKey : undefined,
      // Sync step 3: where this install's internet post box lives, so the QR
      // code can tell the phone. Empty means Wi-Fi only.
      relayUrl: relayClient.readRelayUrl(userDataPath),
      relay: includeSecret ? wsService.relayStatus() : undefined
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

/**
 * Which pairing this PC belongs to, as a short fingerprint of the pairing key
 * (never the key itself; the key cannot be worked out from it). A phone
 * looking for its PC at a new address checks this, so with two PCs running
 * Budget Secure on one network it connects to its own PC and not the other
 * one - which would turn it away and wipe the phone's pairing.
 */
function pairingFingerprint() {
  if (!syncKey) return '';
  return crypto.createHash('sha256').update(`budget-secure-pair-id:${syncKey}`).digest('hex').slice(0, 16);
}

