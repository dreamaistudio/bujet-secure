// POST & DELETE /api/reset - wipe all transactions and settings (Start Fresh)
const handleResetAll = (req, res) => {
  try {
    db.resetAll();
    // Start Fresh makes this PC like a new install, and a new install has no
    // phone paired. So, instead of telling phones to wipe themselves too (a
    // phone keeps its own data), start a new change book and replace the
    // pairing: every phone is told it has been disconnected - over Wi-Fi, or
    // through the post box if it is away - and must scan a new QR code.
    if (wsService.resetChangeBook) wsService.resetChangeBook();
    regenerateSyncToken();
    res.json({ success: true, message: 'All data has been permanently deleted.' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};
router.delete('/reset', handleResetAll);
router.post('/reset', handleResetAll);

